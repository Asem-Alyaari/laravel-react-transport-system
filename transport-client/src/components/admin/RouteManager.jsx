import React, { useState, useEffect } from 'react';
import {
  Route as RouteIcon,
  Plus,
  Edit2,
  Trash2,
  Search,
  MapPin,
  Clock,
  Navigation,
  CheckCircle2,
  AlertCircle,
  RefreshCw,
  Sparkles,
  ArrowRight,
} from 'lucide-react';
import api from '../../api/axios';
import { Card, CardContent } from '../ui/card';
import {
  Table,
  TableHeader,
  TableBody,
  TableHead,
  TableRow,
  TableCell,
} from '../ui/table';
import { Button } from '../ui/button';
import { Input } from '../ui/input';
import { Badge } from '../ui/badge';
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogFooter,
} from '../ui/dialog';

// تحويل الدقائق إلى صيغة نصية عربية واضحة
const formatArabicDuration = (totalMinutes) => {
  if (!totalMinutes && totalMinutes !== 0) return '—';
  const mins = parseInt(totalMinutes, 10);
  if (isNaN(mins) || mins <= 0) return '—';

  const hours = Math.floor(mins / 60);
  const remainingMinutes = mins % 60;

  let hoursText = '';
  if (hours === 1) hoursText = 'ساعة واحدة';
  else if (hours === 2) hoursText = 'ساعتان';
  else if (hours >= 3 && hours <= 10) hoursText = `${hours} ساعات`;
  else if (hours > 10) hoursText = `${hours} ساعة`;

  let minsText = '';
  if (remainingMinutes === 1) minsText = 'دقيقة واحدة';
  else if (remainingMinutes === 2) minsText = 'دقيقتان';
  else if (remainingMinutes >= 3 && remainingMinutes <= 10) minsText = `${remainingMinutes} دقائق`;
  else if (remainingMinutes > 10) minsText = `${remainingMinutes} دقيقة`;

  if (hoursText && minsText) return `${hoursText} و ${minsText}`;
  if (hoursText) return hoursText;
  if (minsText) return minsText;
  return '—';
};

export default function RouteManager() {
  const [routes, setRoutes] = useState([]);
  const [stations, setStations] = useState([]);
  const [loading, setLoading] = useState(true);
  const [searchTerm, setSearchTerm] = useState('');
  const [statusFilter, setStatusFilter] = useState('');

  // حالة النافذة المنبثقة
  const [showModal, setShowModal] = useState(false);
  const [editingRoute, setEditingRoute] = useState(null);
  const [isNameAutoGenerated, setIsNameAutoGenerated] = useState(true);

  const [formData, setFormData] = useState({
    name: '',
    origin_station_id: '',
    destination_station_id: '',
    distance_km: '',
    estimated_duration_minutes: '',
    is_active: true,
  });

  const [submitting, setSubmitting] = useState(false);
  const [errorMsg, setErrorMsg] = useState('');
  const [successMsg, setSuccessMsg] = useState('');

  // جلب المحطات المتاحة
  const fetchStations = () => {
    api
      .get('/stations')
      .then((res) => {
        if (res.data?.status === 'success') {
          setStations(res.data.data || []);
        }
      })
      .catch((err) => console.error('خطأ في جلب المحطات:', err));
  };

  // جلب المسارات مع الفلترة والبحث
  const fetchRoutes = () => {
    setLoading(true);
    api
      .get('/routes', {
        params: {
          search: searchTerm || undefined,
          is_active: statusFilter === '' ? undefined : statusFilter === 'active',
        },
      })
      .then((res) => {
        if (res.data?.status === 'success') {
          setRoutes(res.data.data || []);
        }
      })
      .catch((err) => console.error('خطأ في جلب المسارات:', err))
      .finally(() => setLoading(false));
  };

  useEffect(() => {
    fetchStations();
  }, []);

  useEffect(() => {
    fetchRoutes();
  }, [statusFilter]);

  const handleSearchSubmit = (e) => {
    e.preventDefault();
    fetchRoutes();
  };

  // اقتراح اسم المسار تلقائياً بناءً على محطتي البداية والنهاية
  const generateRouteName = (origId, destId) => {
    const orig = stations.find((s) => String(s.id) === String(origId));
    const dest = stations.find((s) => String(s.id) === String(destId));

    if (orig && dest) {
      const origName = orig.city || orig.name_ar;
      const destName = dest.city || dest.name_ar;
      return `${origName} - ${destName} السريع`;
    }
    return '';
  };

  const handleOriginChange = (origId) => {
    const updated = { ...formData, origin_station_id: origId };
    if (isNameAutoGenerated || !formData.name) {
      const suggested = generateRouteName(origId, formData.destination_station_id);
      if (suggested) {
        updated.name = suggested;
      }
    }
    setFormData(updated);
  };

  const handleDestinationChange = (destId) => {
    const updated = { ...formData, destination_station_id: destId };
    if (isNameAutoGenerated || !formData.name) {
      const suggested = generateRouteName(formData.origin_station_id, destId);
      if (suggested) {
        updated.name = suggested;
      }
    }
    setFormData(updated);
  };

  const handleOpenAdd = () => {
    setEditingRoute(null);
    setIsNameAutoGenerated(true);
    setFormData({
      name: '',
      origin_station_id: '',
      destination_station_id: '',
      distance_km: '',
      estimated_duration_minutes: '',
      is_active: true,
    });
    setErrorMsg('');
    setShowModal(true);
  };

  const handleOpenEdit = (route) => {
    setEditingRoute(route);
    setIsNameAutoGenerated(false);
    setFormData({
      name: route.name || '',
      origin_station_id: route.origin_station_id || route.origin_station?.id || '',
      destination_station_id: route.destination_station_id || route.destination_station?.id || '',
      distance_km: route.distance_km || '',
      estimated_duration_minutes: route.estimated_duration_minutes || '',
      is_active: Boolean(route.is_active),
    });
    setErrorMsg('');
    setShowModal(true);
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setErrorMsg('');

    if (formData.origin_station_id === formData.destination_station_id) {
      setErrorMsg('لا يمكن أن تكون محطة الانطلاق والوصول هي نفس المحطة');
      return;
    }

    setSubmitting(true);

    const payload = {
      name: formData.name.trim(),
      origin_station_id: parseInt(formData.origin_station_id, 10),
      destination_station_id: parseInt(formData.destination_station_id, 10),
      distance_km: parseFloat(formData.distance_km),
      estimated_duration_minutes: parseInt(formData.estimated_duration_minutes, 10),
      is_active: formData.is_active,
    };

    try {
      if (editingRoute) {
        await api.put(`/routes/${editingRoute.id}`, payload);
        setSuccessMsg('تم تحديث بيانات خط السير بنجاح');
      } else {
        await api.post('/routes', payload);
        setSuccessMsg('تم إنشاء خط السير الجديد بنجاح');
      }

      setShowModal(false);
      fetchRoutes();
      setTimeout(() => setSuccessMsg(''), 4000);
    } catch (err) {
      setErrorMsg(err.response?.data?.message || 'حدث خطأ أثناء حفظ المسار');
    } finally {
      setSubmitting(false);
    }
  };

  const handleDelete = async (route) => {
    if (!window.confirm(`هل أنت متأكد من حذف مسار "${route.name}"؟`)) return;

    try {
      await api.delete(`/routes/${route.id}`);
      setSuccessMsg('تم حذف خط السير بنجاح');
      fetchRoutes();
      setTimeout(() => setSuccessMsg(''), 4000);
    } catch (err) {
      alert(err.response?.data?.message || 'تعذر حذف المسار');
    }
  };

  return (
    <div className="space-y-6">
      {/* إشعار النجاح */}
      {successMsg && (
        <div className="flex items-center gap-2 p-4 rounded-xl bg-emerald-50 border border-emerald-200 text-emerald-800 text-sm font-medium animate-in fade-in">
          <CheckCircle2 className="h-5 w-5 text-emerald-600 shrink-0" />
          <span>{successMsg}</span>
        </div>
      )}

      {/* شريط الإجراءات والبحث */}
      <Card>
        <CardContent className="p-4 flex flex-col md:flex-row gap-4 items-center justify-between">
          <form onSubmit={handleSearchSubmit} className="flex gap-2 w-full md:max-w-md">
            <Input
              type="text"
              placeholder="بحث باسم المسار أو المدينة..."
              value={searchTerm}
              onChange={(e) => setSearchTerm(e.target.value)}
              className="h-10"
            />
            <Button type="submit" variant="secondary" className="gap-1.5 shrink-0">
              <Search className="h-4 w-4" />
              <span>بحث</span>
            </Button>
          </form>

          <div className="flex items-center gap-3 w-full md:w-auto justify-end">
            <select
              value={statusFilter}
              onChange={(e) => setStatusFilter(e.target.value)}
              className="h-10 rounded-xl border border-slate-200 bg-white px-3 text-xs font-semibold text-slate-700 focus:outline-none focus:ring-2 focus:ring-blue-500"
            >
              <option value="">جميع المسارات</option>
              <option value="active">مسارات نشطة</option>
              <option value="inactive">مسارات معطلة</option>
            </select>

            <Button onClick={handleOpenAdd} className="gap-2 shrink-0">
              <Plus className="h-4 w-4" />
              <span>إضافة مسار جديد</span>
            </Button>
          </div>
        </CardContent>
      </Card>

      {/* جدول المسارات */}
      <Card className="overflow-hidden">
        {loading ? (
          <div className="py-16 text-center text-slate-500 text-sm font-medium flex flex-col items-center justify-center gap-3">
            <RefreshCw className="h-6 w-6 animate-spin text-blue-600" />
            <span>جاري تحميل بيانات خطوط السير...</span>
          </div>
        ) : routes.length === 0 ? (
          <div className="py-16 text-center text-slate-500 text-sm font-medium">
            لا توجد مسارات مسجلة تطابق معايير البحث.
          </div>
        ) : (
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>اسم المسار</TableHead>
                <TableHead>محطة الانطلاق</TableHead>
                <TableHead>محطة الوصول</TableHead>
                <TableHead>المسافة</TableHead>
                <TableHead>المدة المتوقعة</TableHead>
                <TableHead>نقاط التوقف</TableHead>
                <TableHead>الحالة</TableHead>
                <TableHead className="text-center">الإجراءات</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {routes.map((route) => (
                <TableRow key={route.id}>
                  {/* اسم المسار */}
                  <TableCell className="font-bold text-slate-900">
                    <div className="flex items-center gap-2.5">
                      <div className="h-9 w-9 rounded-xl bg-indigo-50 text-indigo-600 flex items-center justify-center shrink-0">
                        <RouteIcon className="h-4.5 w-4.5" />
                      </div>
                      <div>
                        <span className="block text-sm font-bold text-slate-900">
                          {route.name}
                        </span>
                        <span className="block text-[11px] font-mono text-slate-400">
                          مسار رقم #{route.id}
                        </span>
                      </div>
                    </div>
                  </TableCell>

                  {/* محطة الانطلاق */}
                  <TableCell>
                    <div className="flex items-center gap-1.5">
                      <MapPin className="h-4 w-4 text-blue-500 shrink-0" />
                      <div>
                        <span className="font-bold text-xs text-slate-800 block">
                          {route.origin_station?.name_ar || route.origin_station?.name || 'غير محدد'}
                        </span>
                        <span className="text-[11px] text-slate-500 block">
                          {route.origin_station?.city || ''}
                        </span>
                      </div>
                    </div>
                  </TableCell>

                  {/* محطة الوصول */}
                  <TableCell>
                    <div className="flex items-center gap-1.5">
                      <MapPin className="h-4 w-4 text-emerald-500 shrink-0" />
                      <div>
                        <span className="font-bold text-xs text-slate-800 block">
                          {route.destination_station?.name_ar || route.destination_station?.name || 'غير محدد'}
                        </span>
                        <span className="text-[11px] text-slate-500 block">
                          {route.destination_station?.city || ''}
                        </span>
                      </div>
                    </div>
                  </TableCell>

                  {/* المسافة */}
                  <TableCell>
                    <span className="font-mono font-bold text-slate-800 text-xs">
                      {route.distance_km} كم
                    </span>
                  </TableCell>

                  {/* المدة المتوقعة */}
                  <TableCell>
                    <div className="flex items-center gap-1.5 text-xs font-medium text-slate-700">
                      <Clock className="h-3.5 w-3.5 text-slate-400 shrink-0" />
                      <span>{formatArabicDuration(route.estimated_duration_minutes)}</span>
                    </div>
                  </TableCell>

                  {/* نقاط التوقف */}
                  <TableCell>
                    <span className="text-xs font-semibold text-slate-700">
                      {route.stops_count ?? 0} محطات
                    </span>
                  </TableCell>

                  {/* الحالة */}
                  <TableCell>
                    <Badge variant={route.is_active ? 'success' : 'destructive'}>
                      {route.is_active ? 'نشط' : 'معطل'}
                    </Badge>
                  </TableCell>

                  {/* الإجراءات */}
                  <TableCell className="text-center">
                    <div className="flex items-center justify-center gap-1.5">
                      <Button
                        size="icon"
                        variant="ghost"
                        onClick={() => handleOpenEdit(route)}
                        title="تعديل المسار"
                        className="h-8 w-8 text-blue-600 hover:bg-blue-50"
                      >
                        <Edit2 className="h-4 w-4" />
                      </Button>
                      <Button
                        size="icon"
                        variant="ghost"
                        onClick={() => handleDelete(route)}
                        title="حذف المسار"
                        className="h-8 w-8 text-red-600 hover:bg-red-50"
                      >
                        <Trash2 className="h-4 w-4" />
                      </Button>
                    </div>
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        )}
      </Card>

      {/* نافذة الإضافة والتعديل Dialog */}
      <Dialog open={showModal} onClose={() => setShowModal(false)}>
        <DialogContent className="max-w-xl p-0 overflow-hidden" onClose={() => setShowModal(false)}>
          <DialogHeader className="p-6 pb-4">
            <DialogTitle className="flex items-center gap-2 text-slate-900">
              <RouteIcon className="h-5 w-5 text-blue-600" />
              <span>{editingRoute ? 'تعديل بيانات خط السير' : 'إضافة خط سير ومسار جديد'}</span>
            </DialogTitle>
          </DialogHeader>

          <form onSubmit={handleSubmit}>
            <div className="p-6 pt-2 space-y-4 max-h-[70vh] overflow-y-auto">
              {errorMsg && (
                <div className="flex items-center gap-2 p-3 rounded-xl bg-red-50 border border-red-200 text-red-700 text-xs">
                  <AlertCircle className="h-4 w-4 shrink-0" />
                  <span>{errorMsg}</span>
                </div>
              )}

              {/* محطة الانطلاق والوصول */}
              <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
                <div className="space-y-1.5">
                  <label className="text-xs font-bold text-slate-700">محطة الانطلاق (المغادرة) *</label>
                  <select
                    value={formData.origin_station_id}
                    onChange={(e) => handleOriginChange(e.target.value)}
                    className="flex h-11 w-full rounded-xl border border-slate-200 bg-white px-3 text-xs font-semibold text-slate-800 focus:outline-none focus:ring-2 focus:ring-blue-500"
                    required
                  >
                    <option value="">-- اختر محطة المغادرة --</option>
                    {stations.map((s) => (
                      <option key={s.id} value={s.id}>
                        {s.name_ar} ({s.city}) - {s.code}
                      </option>
                    ))}
                  </select>
                </div>

                <div className="space-y-1.5">
                  <label className="text-xs font-bold text-slate-700">محطة الوصول (الوجهة) *</label>
                  <select
                    value={formData.destination_station_id}
                    onChange={(e) => handleDestinationChange(e.target.value)}
                    className="flex h-11 w-full rounded-xl border border-slate-200 bg-white px-3 text-xs font-semibold text-slate-800 focus:outline-none focus:ring-2 focus:ring-blue-500"
                    required
                  >
                    <option value="">-- اختر محطة الوصول --</option>
                    {stations.map((s) => (
                      <option key={s.id} value={s.id}>
                        {s.name_ar} ({s.city}) - {s.code}
                      </option>
                    ))}
                  </select>
                </div>
              </div>

              {/* اسم المسار واقتراحه */}
              <div className="space-y-1.5">
                <div className="flex items-center justify-between">
                  <label className="text-xs font-bold text-slate-700">اسم المسار / خط السير *</label>
                  {formData.origin_station_id && formData.destination_station_id && (
                    <button
                      type="button"
                      onClick={() => {
                        const sug = generateRouteName(
                          formData.origin_station_id,
                          formData.destination_station_id
                        );
                        if (sug) {
                          setFormData({ ...formData, name: sug });
                          setIsNameAutoGenerated(true);
                        }
                      }}
                      className="text-[11px] text-blue-600 hover:text-blue-800 flex items-center gap-1 font-semibold cursor-pointer"
                    >
                      <Sparkles className="h-3 w-3" />
                      <span>اقتراح الاسم تلقائياً</span>
                    </button>
                  )}
                </div>
                <Input
                  type="text"
                  placeholder="مثال: الرياض - جدة السريع"
                  value={formData.name}
                  onChange={(e) => {
                    setIsNameAutoGenerated(false);
                    setFormData({ ...formData, name: e.target.value });
                  }}
                  required
                />
              </div>

              {/* المسافة والمدة بالدقائق */}
              <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
                <div className="space-y-1.5">
                  <label className="text-xs font-bold text-slate-700">المسافة (كيلومتر) *</label>
                  <Input
                    type="number"
                    step="0.1"
                    min="1"
                    placeholder="مثال: 950"
                    value={formData.distance_km}
                    onChange={(e) => setFormData({ ...formData, distance_km: e.target.value })}
                    required
                  />
                </div>

                <div className="space-y-1.5">
                  <label className="text-xs font-bold text-slate-700">المدة المتوقعة (بالدقائق) *</label>
                  <Input
                    type="number"
                    min="1"
                    placeholder="مثال: 570 (9 ساعات ونصف)"
                    value={formData.estimated_duration_minutes}
                    onChange={(e) =>
                      setFormData({ ...formData, estimated_duration_minutes: e.target.value })
                    }
                    required
                  />
                  {formData.estimated_duration_minutes && (
                    <span className="text-[11px] text-slate-500 block">
                      المعادلة: {formatArabicDuration(formData.estimated_duration_minutes)}
                    </span>
                  )}
                </div>
              </div>

              {/* الحالة التشغيلية */}
              <div className="pt-2">
                <label className="flex items-center gap-3 p-3 rounded-xl border border-slate-200 bg-slate-50/50 hover:bg-slate-50 cursor-pointer select-none transition-colors">
                  <input
                    type="checkbox"
                    checked={formData.is_active}
                    onChange={(e) => setFormData({ ...formData, is_active: e.target.checked })}
                    className="h-4 w-4 rounded text-blue-600 focus:ring-blue-500 border-slate-300"
                  />
                  <div>
                    <span className="text-xs font-bold text-slate-800 block">مسار نشط ومتاح للجدولة</span>
                    <span className="text-[11px] text-slate-500 block">
                      عند التفعيل، يمكن إنشاء وجدولة رحلات على هذا الخط وربطه بالحافلات والسائقين.
                    </span>
                  </div>
                </label>
              </div>
            </div>

            <DialogFooter className="p-4 bg-slate-50 border-t border-slate-100 flex items-center justify-end gap-2">
              <Button type="button" variant="outline" onClick={() => setShowModal(false)}>
                إلغاء
              </Button>
              <Button type="submit" disabled={submitting}>
                {submitting ? 'جاري الحفظ...' : editingRoute ? 'تحديث بيانات المسار' : 'إنشاء المسار'}
              </Button>
            </DialogFooter>
          </form>
        </DialogContent>
      </Dialog>
    </div>
  );
}
